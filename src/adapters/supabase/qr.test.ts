import { describe, expect, it } from "vitest";

import { QR_MAX_LENGTH, qrImage } from "./qr";

// Lo que Supabase Auth manda como código QR al dar de alta un factor, y lo que de eso se
// le entrega a una pantalla: un SVG hecho solo de lo que se espera, o nada. Lo que manda de
// verdad el Auth local se mide en `tests/integration/42-auth-segundo-factor.test.ts`.

const RECT = '<rect x="12" y="15" width="3" height="3" style="fill:black;stroke:none" />';
const OPEN = '<svg width="231" height="231"\n     xmlns="http://www.w3.org/2000/svg"\n     xmlns:xlink="http://www.w3.org/1999/xlink">';
const SVG = `${OPEN}\n${RECT}\n${RECT.replace("black", "white")}\n</svg>`;
/** Como lo manda Auth: declaración, comentario, y el dibujo. */
const FROM_AUTH = `<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n${SVG}\n`;

describe("la imagen del código QR", () => {
  it.each([
    ["como lo manda Auth", FROM_AUTH],
    ["un SVG a secas", SVG],
    ["con espacios delante y detrás", `\n  ${SVG}\n\n`],
    ["con tabuladores y retornos por espacio", `<?xml version="1.0"\t?>\r\n<svg\twidth="1"\r\n>\r\n<rect\tx="1"\r\n/>\t</svg>\r\n`],
    ["con dos comentarios", `<!-- a --><!-- b -->${SVG}`],
    ["con un comentario vacío", `<!---->${SVG}`],
    ["con guiones sueltos en un comentario", `<!-- a-b - c -->${SVG}`],
    ["con la codificación declarada", `<?xml version="1.0" encoding="UTF-8"?>${SVG}`],
    ["sin ningún rectángulo", "<svg></svg>"],
    ["con colores en hexadecimal y rectángulos sin espacio antes del cierre", '<svg><rect x="0" y="0" width="1.5" height="1.5" fill="#000"/></svg>'],
    ["con caja de vista", '<svg viewBox="0 0 231 231" xmlns="http://www.w3.org/2000/svg"></svg>'],
  ])("%s se entrega tal cual", (_what, svg) => {
    expect(qrImage(svg)).toBe(svg);
  });

  it.each([
    ["nada", undefined],
    ["nulo", null],
    ["vacío", ""],
    ["un número", 12345],
    ["un objeto", { svg: SVG }],
    // Lo que al convertirse a texto daría un SVG tampoco es uno.
    ["una lista con un SVG dentro", [SVG]],
    ["un objeto que se hace pasar por texto", { toString: () => SVG }],
    ["texto que no es un SVG", "otpauth://totp/x?secret=JBSWY3DPEHPK3PXP"],
    ["HTML con un SVG dentro", `<html><body>${SVG}</body></html>`],
    ["una dirección de datos", `data:image/svg+xml;utf8,${SVG}`],
    ["algo que solo empieza parecido", "<svgx></svgx>"],
    ["un comentario sin cerrar delante", `<!-- ${SVG}`],
    ["un SVG sin cerrar", `${OPEN}${RECT}`],
    ["solo un cierre", "</svg>"],
    ["rectángulos sin su svg", `${RECT}</svg>`],
    ["dos declaraciones", `<?xml version="1.0"?><?xml version="1.0"?>${SVG}`],
    ["la declaración después de un comentario", `<!-- a --><?xml version="1.0"?>${SVG}`],
    ["una declaración de tipo a secas", `<!DOCTYPE svg>${SVG}`],
    ["una declaración de tipo con entidades", `<!DOCTYPE svg [<!ENTITY x "y">]>${SVG}`],
    // Lo que ya no es XML se pintaría como imagen rota: mejor nada, y la clave en texto.
    ["un salto de línea antes de la declaración", `\n${FROM_AUTH}`],
    ["un comentario con dos guiones seguidos", `<!-- a -- b -->${SVG}`],
    ["un comentario que cierra con tres guiones", `<!-- a --->${SVG}`],
    ["un comentario de puros guiones", `<!------->${SVG}`],
    // El espacio es el de XML, no todo lo que JavaScript llama espacio.
    ["un espacio duro delante", ` ${SVG}`],
    ["una marca de orden de bytes delante", `﻿${FROM_AUTH}`],
    ["un espacio duro en la declaración", `<?xml version="1.0" ?>${SVG}`],
    ["un espacio duro entre el svg y su atributo", '<svg width="1"></svg>'],
    ["un espacio duro antes de cerrar la etiqueta del svg", '<svg width="1" ></svg>'],
    ["un espacio duro entre un rectángulo y su atributo", '<svg><rect x="1"/></svg>'],
    ["un espacio duro antes de cerrar un rectángulo", '<svg><rect x="1" /></svg>'],
    ["un salto de página entre rectángulos", `<svg>${RECT}\f${RECT}</svg>`],
  ])("%s no es una imagen: no se entrega nada", (_what, value) => {
    expect(qrImage(value)).toBeNull();
  });

  // Va por lista de permitidos: un `<svg>` y rectángulos, con sus atributos de posición,
  // tamaño y relleno. Se pinta como imagen, donde nada de esto correría; aun así, lo que
  // trae cualquier otra cosa no se le pasa a ninguna pantalla.
  it.each([
    ["un guion", SVG.replace("<rect", "<script>alert(1)</script><rect")],
    ["un guion en mayúsculas", SVG.replace("<rect", "<SCRIPT>alert(1)</SCRIPT><rect")],
    ["un manejador de eventos", SVG.replace("<rect", '<rect onload="alert(1)"')],
    ["un manejador sin espacio delante", SVG.replace('y="15"', 'y="15"onclick="x"')],
    ["un manejador en el svg", SVG.replace("<svg", '<svg onload="alert(1)"')],
    // El nombre del atributo es lo que cuenta, no lo que traiga dentro.
    ["un manejador en el svg, con un valor inofensivo", SVG.replace("<svg", '<svg onload="x"')],
    ["un manejador en un rectángulo, con un valor inofensivo", SVG.replace("<rect", '<rect onclick="x"')],
    ["dos atributos pegados, sin espacio entre ellos", SVG.replace('x="12" y="15"', 'x="12"y="15"')],
    ["dos atributos del svg pegados", SVG.replace('width="231" height="231"', 'width="231"height="231"')],
    ["un grupo con manejador y barra", SVG.replace("<rect", "<g/onload=alert(1)><rect")],
    ["una imagen dentro", SVG.replace("<rect", '<image href="https://otro.example/x.png"/><rect')],
    ["una referencia a otro documento", SVG.replace("<rect", '<use href="https://otro.example/x.svg#a"/><rect')],
    ["un enlace con una dirección de guion", SVG.replace("<rect", '<a href="javascript:alert(1)"><rect')],
    ["la misma dirección disfrazada con entidades", SVG.replace("<rect", '<a href="&#106;avascript:alert(1)"/><rect')],
    ["una hoja de estilos", SVG.replace("<rect", "<style>@import url(https://otro.example/x.css)</style><rect")],
    ["un estilo que carga algo", SVG.replace("fill:black", "fill:url(https://otro.example/x)")],
    ["contenido ajeno incrustado", SVG.replace("<rect", "<foreignObject><p>x</p></foreignObject><rect")],
    ["un marco", SVG.replace("<rect", '<iframe src="https://otro.example"></iframe><rect')],
    ["texto entre los rectángulos", SVG.replace("<rect", "hola<rect")],
    ["un SVG dentro de otro", SVG.replace("<rect", "<svg></svg><rect")],
    ["un rectángulo con contenido", SVG.replace(" />", "></rect>")],
    ["un atributo con comillas simples", SVG.replace('x="12"', "x='12'")],
    ["un atributo sin comillas", SVG.replace('x="12"', "x=12")],
    ["un atributo que no es de la lista", SVG.replace('x="12"', 'id="a" x="12"')],
    ["un valor con una entidad", SVG.replace('x="12"', 'x="&#49;2"')],
    ["algo después del cierre", `${SVG}<script>alert(1)</script>`],
    ["otro dibujo después del cierre", `${SVG}${SVG}`],
    ["un comentario dentro del dibujo", SVG.replace("<rect", "<!-- a --><rect")],
    ["un comentario después del cierre", `${SVG}<!-- a -->`],
    ["un comentario con una etiqueta dentro", `<!-- <script>x</script> -->${SVG}`],
  ])("con %s no se entrega", (_what, svg) => {
    expect(qrImage(svg)).toBeNull();
  });

  it("tiene tope de tamaño, y el de Auth cabe con holgura", () => {
    expect(QR_MAX_LENGTH).toBe(1_000_000);
    const padded = (length: number) => {
      const fixed = "<!---->".length + SVG.length;
      return `<!--${"x".repeat(length - fixed)}-->${SVG}`;
    };
    expect(padded(QR_MAX_LENGTH)).toHaveLength(QR_MAX_LENGTH);
    expect(qrImage(padded(QR_MAX_LENGTH))).not.toBeNull();
    expect(qrImage(padded(QR_MAX_LENGTH + 1))).toBeNull();
    // Uno del tamaño del de Auth: miles de rectángulos.
    const big = `${OPEN}${`${RECT}\n`.repeat(4761)}</svg>`;
    expect(big.length).toBeGreaterThan(350_000);
    expect(qrImage(big)).toBe(big);
  });

  // Reconocer no puede costar más que leer: una respuesta hostil no puede dejar ocupado al
  // servidor. Estas son las formas que hacen estallar a una expresión regular descuidada.
  it.each([
    // Tan larga como cabe: con pocos, un tiempo que creciera con el cuadrado no se notaría.
    ["una fila de comentarios sin dibujo después", `${"<!---->".repeat(140_000)}x`],
    ["un comentario enorme sin cerrar", `<!--${"-".repeat(900_000)}`],
    ["un comentario de guiones sueltos sin cerrar", `<!--${"x-".repeat(450_000)}`],
    ["un comentario de letras sin cerrar", `<!--${"x".repeat(900_000)}`],
    ["espacios y más espacios", `${" ".repeat(900_000)}x`],
    ["un svg con miles de atributos y sin cerrar", `<svg${' width="1"'.repeat(50_000)}`],
    ["miles de rectángulos y al final algo que no es", `${OPEN}${RECT.repeat(10_000)}<x/></svg>`],
    ["un rectángulo con miles de atributos y sin cerrar", `<svg><rect${' x="1"'.repeat(50_000)}`],
  ])("%s se rechaza enseguida", (_what, hostile) => {
    const started = performance.now();
    expect(qrImage(hostile)).toBeNull();
    expect(performance.now() - started).toBeLessThan(500);
  });
});
