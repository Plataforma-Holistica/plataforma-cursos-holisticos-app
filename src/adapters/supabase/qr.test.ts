import { describe, expect, it } from "vitest";

import { QR_MAX_LENGTH, qrImage } from "./qr";

// Lo que Supabase Auth manda como código QR al dar de alta un factor, y lo que de eso se
// le entrega a una pantalla. Lo que manda de verdad el Auth local se mide en
// `tests/integration/42-auth-segundo-factor.test.ts`.

const SVG = '<svg width="231" height="231" xmlns="http://www.w3.org/2000/svg"><rect x="0" y="0" width="7" height="7"/></svg>';

describe("la imagen del código QR", () => {
  it.each([
    ["un SVG a secas", SVG],
    ["con su declaración de XML y un comentario delante, como lo manda Auth", `<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n${SVG}`],
    ["con espacios delante", `\n  ${SVG}`],
    ["con dos comentarios", `<!-- a --><!-- b -->${SVG}`],
  ])("%s se entrega tal cual", (_what, svg) => {
    expect(qrImage(svg)).toBe(svg);
  });

  it.each([
    ["nada", undefined],
    ["nulo", null],
    ["vacío", ""],
    ["un número", 12345],
    ["un objeto", { svg: SVG }],
    // Lo que al convertirse a texto daría un SVG tampoco es uno.
    ["una lista con un SVG dentro", [SVG]],
    ["un objeto que se hace pasar por texto", { toString: () => SVG }],
    ["texto que no es un SVG", "otpauth://totp/x?secret=JBSWY3DPEHPK3PXP"],
    ["HTML con un SVG dentro", `<html><body>${SVG}</body></html>`],
    ["una dirección de datos", `data:image/svg+xml;utf8,${SVG}`],
    ["algo que solo empieza parecido", "<svgx></svgx>"],
    ["un comentario sin cerrar delante", `<!-- ${SVG}`],
  ])("%s no es una imagen: no se entrega nada", (_what, value) => {
    expect(qrImage(value)).toBeNull();
  });

  // Se pinta como imagen, donde un SVG no ejecuta nada. Aun así, lo que trae algo más que
  // dibujo no se le pasa a ninguna pantalla.
  it.each([
    ["un guion", SVG.replace("<rect", "<script>alert(1)</script><rect")],
    ["un guion en mayúsculas", SVG.replace("<rect", "<SCRIPT>alert(1)</SCRIPT><rect")],
    ["un manejador de eventos", SVG.replace("<rect", '<rect onload="alert(1)"')],
    ["un manejador con espacios", SVG.replace("<rect", '<rect onclick = "x()"')],
    ["contenido ajeno incrustado", SVG.replace("<rect", "<foreignObject><p>x</p></foreignObject><rect")],
    ["una dirección de guion", SVG.replace("<rect", '<a href="javascript:alert(1)"><rect')],
  ])("con %s no se entrega", (_what, svg) => {
    expect(qrImage(svg)).toBeNull();
  });

  it("uno desmedido tampoco: tiene tope", () => {
    const filler = "<!-- " + "x".repeat(QR_MAX_LENGTH) + " -->";
    expect(qrImage(SVG.replace("</svg>", `${filler}</svg>`))).toBeNull();
    const fits = SVG.replace("</svg>", `<!-- ${"x".repeat(1000)} --></svg>`);
    expect(qrImage(fits)).toBe(fits);
    // El que manda el Auth local pesa unos 360 KB: cabe con holgura.
    expect(QR_MAX_LENGTH).toBe(1_000_000);
    expect(qrImage("<svg>" + "x".repeat(QR_MAX_LENGTH - 5))).not.toBeNull();
    expect(qrImage("<svg>" + "x".repeat(QR_MAX_LENGTH - 4))).toBeNull();
  });
});
